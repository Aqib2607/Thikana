    /**
     * Run the property listings database seeder.
     */
    public function run(): void
    {
        $admin = User::where('email', 'admin@demo.test')->first();
        $landlords = User::where('email', 'like', 'landlord%@demo.test')
            ->orderBy('id')
            ->get();

        if ($landlords->isEmpty()) {
            return;
        }

        $amenities = Amenity::all();
        $areas = Area::all()->keyBy('name');

        $propertiesDefinition = $this->getPropertiesDefinition();

        foreach ($propertiesDefinition as $index => $def) {
            $landlord = $landlords[$def['landlord_index'] % $landlords->count()];
            $area = $areas->get($def['area']);
            $lat = $area ? ((float) $area->lat + ($def['lat_offset'] ?? 0.0005)) : 22.8456000;
            $lng = $area ? ((float) $area->lng + ($def['lng_offset'] ?? 0.0005)) : 89.5403000;

            // 1. Create or Update Core Property Listing
            /** @var Property $property */
            $property = Property::updateOrCreate(
                ['slug' => $def['slug']],
                [
                    'landlord_id' => $landlord->id,
                    'title' => $def['title'],
                    'bangla_title' => $def['bangla_title'],
                    'property_type' => $def['property_type'],
                    'rental_type' => $def['rental_type'],
                    'rent' => $def['rent'],
                    'advance' => $def['advance'],
                    'additional_charges' => $def['additional_charges'],
                    'bills_included' => $def['bills_included'],
                    'availability' => $def['availability'],
                    'available_from' => $def['available_from'],
                    'approval_status' => $def['approval_status'],
                    'size' => $def['size'],
                    'rooms' => $def['rooms'],
                    'bathrooms' => $def['bathrooms'],
                    'balconies' => $def['balconies'],
                    'floor' => $def['floor'],
                    'total_floors' => $def['total_floors'],
                    'furnished_status' => $def['furnished_status'],
                    'preferred_tenant' => $def['preferred_tenant'],
                    'public_contact_visible' => $def['public_contact_visible'],
                    'community_info' => $def['community_info'],
                    'rating' => $def['rating'],
                    'review_count' => $def['review_count'],
                ]
            );

            // 2. Exact 1:1 Location Hierarchy
            PropertyLocation::updateOrCreate(
                ['property_id' => $property->id],
                [
                    'division' => 'Khulna',
                    'district' => 'Khulna',
                    'city' => 'Khulna',
                    'area' => $def['area'],
                    'exact_address' => $def['address'],
                    'lat' => $lat,
                    'lng' => $lng,
                ]
            );

            // 3. Attach Relevant Amenities (Pivot)
            if ($amenities->isNotEmpty()) {
                $amenitySubset = $amenities->slice($def['amenity_start'] ?? 0, $def['amenity_count'] ?? 6);
                $property->amenities()->sync($amenitySubset->pluck('id')->toArray());
            }

            // 4. Listing Gallery Images (Unsplash external provenance)
            $imageIndices = $def['image_indices'] ?? [0, 1, 2, 3];
            foreach ($imageIndices as $order => $poolIndex) {
                $url = $this->galleryPool[$poolIndex % count($this->galleryPool)];
                PropertyImage::updateOrCreate(
                    [
                        'property_id' => $property->id,
                        'display_order' => $order + 1,
                    ],
                    [
                        'image_url' => $url,
                        'is_featured' => ($order === 0),
                    ]
                );
            }

            // 5. Verifications for Approved Properties
            if ($def['approval_status'] === 'Approved' && ! empty($def['verifications'])) {
                foreach ($def['verifications'] as $vType) {
                    PropertyVerification::firstOrCreate(
                        [
                            'property_id' => $property->id,
                            'verification_type' => $vType,
                        ],
                        [
                            'verified_by' => $admin?->id,
                        ]
                    );
                }
            }
        }
    }

